    private const val ABSOLUTE_THRESHOLD = 80_000

    /**
     * Slå upp månatligt skatteavdrag enligt skattetabell 35 (2026), kolumn 1.
     *
     * @param monthlySalary Bruttolön för månaden i kronor
     * @return Skatteavdrag i kronor
     */
    fun lookupMonthlyTax(monthlySalary: Double): Double {
        if (monthlySalary <= 0) return 0.0

        val salary = monthlySalary.toInt()

        // Binary search for the first entry where upperBound >= salary
        var low = 0
        var high = table.size - 1
        var result = table.last()

        while (low <= high) {
            val mid = (low + high) / 2
            if (table[mid].first >= salary) {
                result = table[mid]
                high = mid - 1
            } else {
                low = mid + 1
            }
        }

        return if (result.first <= ABSOLUTE_THRESHOLD) {
            // Absolute amount in SEK
            result.second.toDouble()
        } else {
            // Percentage of gross salary
            monthlySalary * result.second / 100.0
        }
    }
